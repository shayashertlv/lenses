"""E5 exact radial preview/AR proof on three private copies, with no providers.

The source inventory is the same private manifest as ``general_edit``. Only its
Oakley shield and Prada pair are selected; the coarse pair is generated by the
existing fixture builder. Circle and moved three-colour oval cases are rendered
serially through the real production parity runner. Source files are read only.
"""
from __future__ import annotations

import argparse
import copy
import hashlib
import json
from pathlib import Path
import subprocess

from glasses3d.agent import procs
from glasses3d.agent.owner_lens_edit import _parse
from glasses3d.agent.owner_look_edit import build_look, map_look, patch_glb, read_materials
from glasses3d.dev_ui.e2e.general_edit import synthetic_assets
from glasses3d.dev_ui.lens_renderer import ensure_renderer_build

REPO = Path(__file__).resolve().parents[3]


def sha(payload):
    return hashlib.sha256(payload).hexdigest()


def linear(hex_colour):
    values = [int(hex_colour[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    return [x / 12.92 if x <= .04045 else ((x + .055) / 1.055) ** 2.4 for x in values]


def variants():
    return {
        "circle": {"direction": "around_point", "centre": [0, 0], "roundness": 1,
            "colours": [{"colour": linear("#20c979"), "share": 58},
                        {"colour": linear("#914de3"), "share": 42}], "blend": .85},
        "moved-oval": {"direction": "around_point", "centre": [.18, -.12], "roundness": 2,
            "colours": [{"colour": linear("#20c979"), "share": 42},
                        {"colour": linear("#25b5d9"), "share": 18},
                        {"colour": linear("#914de3"), "share": 40}], "blend": .65},
        # Gradient v2 (three-layer editor): positioned stops, per-transition softness, tint strength.
        "v2-dark-to-clear": {"version": 2, "direction": "top_to_bottom", "softness": [1],
            "stops": [{"colour": linear("#2a2a2e"), "position": .1, "strength": 1},
                      {"colour": linear("#2a2a2e"), "position": .9, "strength": 0}]},
        "v2-ring": {"version": 2, "direction": "around_point", "centre": [0, .35], "roundness": 1.6,
            "softness": [.9, .2], "stops": [{"colour": linear("#3fbf86"), "position": 0, "strength": 1},
                                           {"colour": linear("#8a5cc8"), "position": .55, "strength": .8},
                                           {"colour": linear("#5a3c8c"), "position": .9, "strength": 1}]},
        "v2-centre-sides": {"version": 2, "direction": "centre_to_sides", "softness": [.6],
            "stops": [{"colour": linear("#3fbf86"), "position": .2, "strength": .7},
                      {"colour": linear("#8a5cc8"), "position": .8, "strength": 1}]},
    }


def prepare(inputs, out):
    rows = json.loads(inputs.read_text(encoding="utf-8"))
    rows += synthetic_assets(out)
    selected = []
    for label in ("oakley-rerun", "prada", "synthetic-pair"):
        matches = [row for row in rows if row["label"] == label]
        assert len(matches) == 1, f"Missing or ambiguous required source: {label}"
        selected.append(matches[0])
    cases = []
    for row in selected:
        source = Path(row["model"]).resolve()
        original = source.read_bytes()
        if row.get("sha256"):
            assert sha(original) == row["sha256"], f"Inventory source changed: {row['label']}"
        dto = read_materials(original)
        for name, spec in variants().items():
            values = {item["material_index"]: {**copy.deepcopy(item["values"]),
                "gradient": copy.deepcopy(spec), "transmission": .82,
                "metallic": .08, "roughness": .2, "iridescence": .25}
                for item in dto["materials"] if item["role"] == "lens"}
            assert values, row["label"]
            payload, receipt = patch_glb(original, values)
            saved = read_materials(payload)
            for item in saved["materials"]:
                if item["material_index"] in values:
                    assert item["values"] == values[item["material_index"]]
                    assert receipt["values"][str(item["material_index"])] == item["values"]
            before_doc, before_chunks = _parse(original)
            after_doc, after_chunks = _parse(payload)
            assert before_doc["nodes"] == after_doc["nodes"]
            for (kind, old, _), (new_kind, new, _) in zip(before_chunks[1:], after_chunks[1:]):
                assert kind == new_kind and new[:len(old)] == old
            for old_mesh, new_mesh in zip(before_doc["meshes"], after_doc["meshes"]):
                for old, new in zip(old_mesh["primitives"], new_mesh["primitives"]):
                    assert old.get("indices") == new.get("indices")
                    assert all(new["attributes"][key] == value for key, value in old["attributes"].items())
            look = build_look(original, values)
            mapping = map_look(look, original, same_job=True, mode="reapply")
            assert not mapping["skipped"]
            reapplied, _ = patch_glb(original, mapping["values"])
            assert reapplied == payload, "Radial reusable look did not reproduce exact bytes"
            stem = f"{row['label']}-{name}"
            model, materials = out / f"{stem}.glb", out / f"{stem}.json"
            model.write_bytes(payload)
            procs.write_json_atomic(materials, saved)
            procs.write_json_atomic(out / f"{stem}-receipt.json", receipt)
            cases.append({"name": stem, "label": row["label"], "variant": name,
                "model": str(model), "materials": str(materials), "gradient": spec,
                "original": str(source), "original_sha256": sha(original),
                "original_binary_ranges_exact": True, "geometry_and_normals_exact": True,
                "receipt_parameters_exact": True, "reapplied_glb_bytes_exact": True})
        assert source.read_bytes() == original
    procs.write_json_atomic(out / "cases.json", cases)
    return cases


def prove(out, cases):
    ensure_renderer_build()
    results = []
    for case in cases:
        print("Radial parity " + case["name"], flush=True)
        destination = out / "renders" / case["name"]
        command = ["node", str(REPO / "glasses3d/dev_ui/lens_renderer/general-parity.mjs"),
                   "--out", str(destination), "--model", case["model"], "--materials", case["materials"]]
        child = subprocess.run(command, cwd=REPO, creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0))
        result = {"name": case["name"], "exit_code": child.returncode}
        if (destination / "parity.json").exists():
            result.update(json.loads((destination / "parity.json").read_text(encoding="utf-8")))
        result["original_source_unchanged"] = sha(Path(case["original"]).read_bytes()) == case["original_sha256"]
        results.append(result)
        procs.write_json_atomic(out / "summary.json", results)
        assert child.returncode == 0 and result["passed"] and result["original_source_unchanged"], case["name"]
    assert len(results) == len(cases) == 3 * len(variants())
    print(f"All {len(results)} gradient parity comparisons passed with zero differing channels.", flush=True)
    return results


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--inputs", type=Path)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--phase", choices=("prepare", "prove", "all"), default="all")
    args = parser.parse_args()
    out = args.out.resolve()
    if not out.is_relative_to(REPO / "glasses3d/data/m12"):
        raise ValueError("Use a new ignored private M12 evidence directory.")
    if args.phase in ("prepare", "all"):
        if args.inputs is None:
            parser.error("--inputs is required when preparing parity fixtures")
        out.mkdir(parents=True, exist_ok=False)
        cases = prepare(args.inputs.resolve(), out)
    else:
        cases = json.loads((out / "cases.json").read_text(encoding="utf-8"))
    if args.phase in ("prove", "all"):
        prove(out, cases)


if __name__ == "__main__":
    main()
